#!/usr/bin/env python3
"""Build a color ramp from the renderer's own colormap definition.

Why this exists
---------------
extract_ramp.py reads a published colorbar PNG. That works where the bar
is generated by the renderer, and fails silently where it is not. On
2026-11-21 the water-level bar verified against its own printed numbers
and explained 0.032% of the pixels in real frames, because the bar is a
hand-made asset with no code path to the plotting script. The QPE bars
have the same problem.

So where the plotting script can be read, its colormap is the better
source. This reproduces matplotlib's `LinearSegmentedColormap.from_list`
and `Normalize` so the table here is the table the frames were painted
with, rather than a picture of one.

What it reproduces
------------------
`from_list(name, colors, N)` spaces the anchors evenly across [0, 1] and
interpolates each channel linearly between them. The lookup table has N
entries, and entry i is the interpolation at i/(N-1).

`imshow(..., vmin, vmax)` normalizes a value v to x = (v-vmin)/(vmax-vmin),
then `Colormap.__call__` takes the entry at `int(x * N)`, clamped to N-1.
So entry i covers the half-open value band
[vmin + (vmax-vmin)*i/N, vmin + (vmax-vmin)*(i+1)/N).

Both of those are asserted against a hand-worked case in
validation_tests/js/test_map_ramps.mjs, because a ramp that is subtly
wrong gives a readout that is confidently wrong.

Excluding a color
-----------------
A renderer that does not mask its fill value paints nodata in a real
ramp color. The CoSMoS level plotters use `np.ma.masked_invalid`, which
masks NaN and inf only, so the -99999 fill survives and clips to vmin.
On water level that is the first anchor, identical to a true -4.00 m, and
no readout can separate the two from color alone. `--exclude-color` drops
those entries so the console reports nothing there instead of reporting
a number that may be nodata.

Usage
-----
::

    python validation_tests/visual/build_ramp_from_anchors.py \\
        --anchors '#6f00ff,#ff00ff,...' --vmin -4 --vmax 10 \\
        --unit m --label 'Water level [m]' --moment WaterLevel \\
        --source 'plot_water_level.py:108 (the CoSMoS host)' \\
        --exclude-color '#6f00ff' \\
        --exclude-reason 'the -99999 fill clips to vmin and lands here' \\
        --out frontend/src/lib/map/ramps/data/aqpi-product-water-level.json
"""
from __future__ import annotations

import argparse
import json
import math
import sys
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

#: How many entries matplotlib's default lookup table carries.
DEFAULT_LEVELS = 256

#: How many decimals a band edge keeps. Five is past any unit these
#: products use and keeps the file diffable.
PLACES = 5


def finite(text: str) -> float:
    """Parse a bound, refusing nan and inf.

    A nan bound makes every band edge nan without raising, and the
    legend then prints blanks beside real colors.

    Args:
        text: The argument as typed.

    Returns:
        The value.

    Raises:
        ArgumentTypeError: If the text is not a finite number.
    """
    try:
        v = float(text)
    except ValueError as exc:
        raise argparse.ArgumentTypeError(f"{text!r} is not a number") from exc
    if not math.isfinite(v):
        raise argparse.ArgumentTypeError(f"{text!r} is not finite")
    return v


def parse_hex(text: str) -> tuple[int, int, int]:
    """Read one #rrggbb color.

    Args:
        text: The color, with or without its leading hash.

    Returns:
        Its channels, each 0 to 255.

    Raises:
        ValueError: When it is not six hex digits.
    """
    raw = text.strip().lstrip("#")
    if len(raw) != 6:
        raise ValueError(f"{text!r} is not a #rrggbb color")
    return (int(raw[0:2], 16), int(raw[2:4], 16), int(raw[4:6], 16))


def to_hex(rgb: tuple[float, float, float]) -> str:
    """Write one color the way the ramp files spell it.

    Matplotlib rounds each channel to the nearest byte when it writes a
    PNG, so this rounds rather than truncates.

    Args:
        rgb: The channels, each 0 to 255.

    Returns:
        The color as #rrggbb, lowercase.
    """
    out = "".join(f"{min(255, max(0, round(c))):02x}" for c in rgb)
    return f"#{out}"


def lookup_table(anchors: list[tuple[int, int, int]],
                 levels: int) -> list[tuple[float, float, float]]:
    """Reproduce LinearSegmentedColormap.from_list's table.

    Args:
        anchors: The colors in order, as matplotlib was given them.
        levels: The table's size, matplotlib's N.

    Returns:
        One color per entry, channels unrounded.

    Raises:
        ValueError: When there are fewer than two anchors or no entries.
    """
    if len(anchors) < 2:
        raise ValueError("a colormap needs at least two anchors")
    if levels < 2:
        raise ValueError("a lookup table needs at least two entries")
    last = len(anchors) - 1
    out: list[tuple[float, float, float]] = []
    for i in range(levels):
        x = i / (levels - 1)
        # Which anchor pair x falls between, and how far along it is.
        pos = x * last
        lo = min(int(pos), last - 1)
        frac = pos - lo
        a = anchors[lo]
        b = anchors[lo + 1]
        out.append(tuple(a[c] + (b[c] - a[c]) * frac  # type: ignore[misc]
                         for c in range(3)))
    return out


def band_edges(norm: str, vmin: float, vmax: float, levels: int,
               boundaries: list[float] | None) -> list[float]:
    """The value each lookup entry starts and ends at.

    Three norms, because the renderers use three.

    `Normalize` maps v to (v-vmin)/(vmax-vmin), so entry i covers an
    equal slice of the range.

    `LogNorm` maps v to (log v - log vmin)/(log vmax - log vmin), so
    entry i covers an equal slice of the log range and the bands are
    geometric. Read as linear instead, the 1.00 tick of an accumulation
    bar reported 12.14 inches.

    `BoundaryNorm` is given its edges outright and entry i covers
    [a[i], a[i+1]). Nothing is interpolated between them, so this is the
    one norm whose bands are exact by construction.

    Args:
        norm: One of linear, log, boundary.
        vmin: The low end, ignored for a boundary norm.
        vmax: The high end, ignored for a boundary norm.
        levels: The lookup table's size, ignored for a boundary norm.
        boundaries: The edges, for a boundary norm.

    Returns:
        levels + 1 edges, low to high.

    Raises:
        ValueError: When the norm cannot describe a scale.
    """
    if norm == "boundary":
        if not boundaries or len(boundaries) < 2:
            raise ValueError("a boundary norm needs at least two edges")
        edges = sorted(set(boundaries))
        if len(edges) != len(boundaries):
            raise ValueError("the boundaries repeat; np.unique them first")
        return edges
    if not vmax > vmin:
        raise ValueError(f"vmin {vmin} is not below vmax {vmax}")
    if norm == "log":
        if vmin <= 0:
            raise ValueError(f"a log norm needs a positive vmin, not {vmin}")
        ratio = vmax / vmin
        return [vmin * ratio ** (i / levels) for i in range(levels + 1)]
    span = vmax - vmin
    return [vmin + span * i / levels for i in range(levels + 1)]


def build_stops(anchors: list[tuple[int, int, int]], edges: list[float],
                levels: int) -> list[dict[str, Any]]:
    """One stop per lookup entry, with the value band it covers.

    Args:
        anchors: The colormap's anchor colors.
        edges: The band edges, one more than there are entries.
        levels: The lookup table's size.

    Returns:
        The stops, low to high.

    Raises:
        ValueError: When the edges do not bound the entries.
    """
    if len(edges) != levels + 1:
        raise ValueError(f"{len(edges)} edges cannot bound {levels} entries")
    table = lookup_table(anchors, levels)
    stops: list[dict[str, Any]] = []
    for i, rgb in enumerate(table):
        lo, hi = edges[i], edges[i + 1]
        stops.append({
            "color": to_hex(rgb),
            "value": round((lo + hi) / 2, PLACES),
            "lo": round(lo, PLACES),
            "hi": round(hi, PLACES)
        })
    return stops


def merge_runs(stops: list[dict[str, Any]]) -> tuple[list[dict[str, Any]], int]:
    """Join neighboring entries that round to the same byte color.

    Quantising a continuous colormap to bytes collides now and then, and
    two neighboring entries painted one color describe one band. Merging
    them keeps the band, since only its edges move, by one entry's
    width. Dropping them would lose a readable part of the scale.

    Args:
        stops: The stops, low to high.

    Returns:
        The merged stops and how many entries were absorbed.
    """
    out: list[dict[str, Any]] = []
    for stop in stops:
        if out and out[-1]["color"] == stop["color"]:
            prev = out[-1]
            prev["hi"] = stop["hi"]
            prev["value"] = round((prev["lo"] + prev["hi"]) / 2, PLACES)
            continue
        out.append(dict(stop))
    return out, len(stops) - len(out)


def drop_ambiguous(
    stops: list[dict[str, Any]]
) -> tuple[list[dict[str, Any]], list[dict[str, Any]]]:
    """Remove colors the colormap uses at two separate values.

    A ramp that turns back on itself paints two different values the
    same color, and no readout can tell them apart from color alone.
    The water-level map does this below zero, where #8500ff is both
    -3.84 m and -2.41 m. Reporting either one is reporting a coin toss,
    so the console reports nothing there.

    Args:
        stops: The stops, already merged.

    Returns:
        The unambiguous stops, and the bands that were dropped.
    """
    seen: dict[str, int] = {}
    for stop in stops:
        seen[stop["color"]] = seen.get(stop["color"], 0) + 1
    repeated = {c for c, n in seen.items() if n > 1}
    kept = [s for s in stops if s["color"] not in repeated]
    gone = [s for s in stops if s["color"] in repeated]
    return kept, gone


def drop_colors(stops: list[dict[str, Any]],
                excluded: list[str]) -> tuple[list[dict[str, Any]], int]:
    """Remove every stop painted in one of the given colors.

    Args:
        stops: The stops to filter.
        excluded: The colors to drop, as #rrggbb.

    Returns:
        The surviving stops and how many were dropped.
    """
    if not excluded:
        return stops, 0
    want = {to_hex(parse_hex(c)) for c in excluded}
    kept = [s for s in stops if s["color"] not in want]
    return kept, len(stops) - len(kept)


def fraction_of(value: float, edges: list[float]) -> float:
    """Where one value sits along a bar drawn from these bands.

    By band rather than by value, because a segmented bar draws every
    band at the same width whatever range it covers. Reading the
    position off the value instead puts every tick of a nine-segment
    accumulation bar in its first tenth.

    Args:
        value: The number the bar prints.
        edges: The band edges, low to high.

    Returns:
        0 at the bar's foot and 1 at its head.
    """
    bands = len(edges) - 1
    if bands < 1:
        return 0.0
    for i in range(bands):
        lo, hi = edges[i], edges[i + 1]
        if lo <= value <= hi:
            within = 0.0 if hi == lo else (value - lo) / (hi - lo)
            return (i + within) / bands
    return 0.0 if value < edges[0] else 1.0


def build(args: argparse.Namespace) -> dict[str, Any]:
    """Assemble the ramp file.

    Args:
        args: The parsed command line.

    Returns:
        The ramp, ready to write.

    Raises:
        ValueError: When the inputs do not describe a colormap.
    """
    anchors = [parse_hex(c) for c in str(args.anchors).split(",") if c.strip()]
    bounds = ([finite(t) for t in str(args.boundaries).split(",") if t.strip()]
              if args.boundaries else None)
    if args.norm == "boundary":
        if not bounds:
            raise ValueError("a boundary norm needs --boundaries")
        # matplotlib's BoundaryNorm takes ncolors = len(boundaries) - 1,
        # and the renderers pass that same number as the colormap's N,
        # so the table's size is the edge count rather than --levels.
        levels = len(sorted(set(bounds))) - 1
    else:
        levels = int(args.levels)
    edges = band_edges(args.norm, args.vmin, args.vmax, levels, bounds)
    stops = build_stops(anchors, edges, levels)
    stops, merged = merge_runs(stops)
    stops, ambiguous = drop_ambiguous(stops)
    stops, dropped = drop_colors(stops, list(args.exclude_color or []))
    if not stops:
        raise ValueError("every stop was excluded")
    ramp: dict[str, Any] = {
        "moment": args.moment,
        "unit": args.unit,
        "label": args.label,
        "min": round(edges[0], PLACES),
        "max": round(edges[-1], PLACES),
        # A boundary norm has no formula between its printed numbers,
        # so its legend places ticks from the measured positions the
        # segmented axis carries.
        "scale": "segmented" if args.norm == "boundary" else args.norm,
        "source": args.source,
        "read_on": datetime.now(timezone.utc).date().isoformat(),
        "built_from": {
            "kind": "LinearSegmentedColormap.from_list",
            "anchors": [to_hex(a) for a in anchors],
            "levels": levels,
            "norm": args.norm,
            "vmin": round(edges[0], PLACES),
            "vmax": round(edges[-1], PLACES)
        },
        "stops": stops
    }
    if args.ticks:
        # A segmented axis has no shape between its printed numbers, so
        # the legend is told where each one sits rather than computing
        # it. These are the renderer's own custom_ticks.
        want = [finite(t) for t in str(args.ticks).split(",") if t.strip()]
        lo, hi = edges[0], edges[-1]
        ramp["ticks"] = [
            {"value": v,
             "fraction": round(fraction_of(v, edges), PLACES)}
            for v in want if lo <= v <= hi
        ]
    if merged:
        ramp["merged_runs"] = merged
    if ambiguous:
        ramp["ambiguous"] = {
            "colors": sorted({str(s["color"]) for s in ambiguous}),
            "bands": [[s["lo"], s["hi"]] for s in ambiguous],
            "reason": "the colormap paints these colors at two separate "
                      "values, so a color cannot name one of them"
        }
    if dropped:
        ramp["excluded"] = {
            "colors": [to_hex(parse_hex(c)) for c in args.exclude_color],
            "stops_dropped": dropped,
            "reason": args.exclude_reason or "ambiguous with nodata"
        }
    return ramp


def main() -> int:
    """Build one ramp and write it.

    Returns:
        0 on success, 1 when the inputs do not describe a colormap.
    """
    ap = argparse.ArgumentParser(description=__doc__)
    _ = ap.add_argument("--anchors", required=True,
                        help="the anchor colors, comma separated")
    _ = ap.add_argument("--vmin", type=finite, default=0.0)
    _ = ap.add_argument("--vmax", type=finite, default=1.0)
    _ = ap.add_argument("--levels", type=int, default=DEFAULT_LEVELS,
                        help="the lookup table's size, matplotlib's N; "
                             "ignored for a boundary norm, which takes it "
                             "from the edge count")
    _ = ap.add_argument("--norm", choices=("linear", "log", "boundary"),
                        default="linear",
                        help="which Normalize the renderer passes")
    _ = ap.add_argument("--boundaries", default="",
                        help="the BoundaryNorm edges, comma separated")
    _ = ap.add_argument("--unit", required=True)
    _ = ap.add_argument("--label", required=True)
    _ = ap.add_argument("--moment", required=True)
    _ = ap.add_argument("--source", required=True,
                        help="where the definition was read, file and line")
    _ = ap.add_argument("--ticks", default="",
                        help="the numbers the bar prints, comma separated")
    _ = ap.add_argument("--exclude-color", action="append", default=[])
    _ = ap.add_argument("--exclude-reason", default="")
    _ = ap.add_argument("--out", type=Path, required=True)
    args = ap.parse_args()

    try:
        ramp = build(args)
    except ValueError as exc:
        print(f"cannot build the ramp: {exc}", file=sys.stderr)
        return 1

    out: Path = args.out
    _ = out.write_text(json.dumps(ramp, indent="\t") + "\n")
    kept = len(ramp["stops"])
    notes: list[str] = []
    if ramp.get("merged_runs"):
        notes.append(f"{ramp['merged_runs']} merged")
    if ramp.get("ambiguous"):
        notes.append(f"{len(ramp['ambiguous']['bands'])} ambiguous dropped")
    if ramp.get("excluded"):
        notes.append(f"{ramp['excluded']['stops_dropped']} excluded")
    note = f" ({', '.join(notes)})" if notes else ""
    print(f"wrote {out} — {kept} stops{note}, "
          f"{ramp['min']} to {ramp['max']} {ramp['unit']}")
    print("now measure it: ramp_coverage.py "
          f"{out} FRAME.png...")
    return 0


if __name__ == "__main__":
    sys.exit(main())
